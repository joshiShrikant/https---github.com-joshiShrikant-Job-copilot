package com.eurojobcopilot.modules.recruiter.dto;

import com.eurojobcopilot.modules.recruiter.entity.CommunicationChannel;
import com.eurojobcopilot.modules.recruiter.entity.RecruiterMessageStatus;
import com.eurojobcopilot.modules.recruiter.entity.RecruiterMessageType;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.Instant;
import java.time.LocalDate;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Logged or AI-drafted communication record with a recruiter contact")
public class RecruiterInteractionDto {

    @Schema(description = "Interaction record ID", example = "42")
    private Long id;

    @Schema(description = "Recruiter ID", example = "7")
    private Long recruiterId;

    @Schema(description = "Recruiter full name", example = "Sophie van Dijk")
    private String recruiterName;

    @Schema(description = "Recruiter company name", example = "Adyen N.V.")
    private String companyName;

    @Schema(description = "Optional linked application UUID")
    private String applicationUuid;

    @Schema(description = "Optional linked job ID")
    private Long jobId;

    @Schema(description = "Optional linked job title")
    private String jobTitle;

    @Schema(description = "Communication channel", example = "EMAIL")
    private CommunicationChannel channel;

    @Schema(description = "Message category", example = "FOLLOW_UP")
    private RecruiterMessageType messageType;

    @Schema(description = "Approval & send lifecycle state (generated drafts start as DRAFT and never auto-send)", example = "DRAFT")
    private RecruiterMessageStatus status;

    @Schema(description = "Optional email or InMail subject line")
    private String subjectLine;

    @Schema(description = "Editable message content")
    private String messageBody;

    @Schema(description = "Timestamp when user explicitly confirmed manual sending (null while unsent)")
    private Instant sentAt;

    @Schema(description = "Timestamp when user explicitly approved the draft")
    private Instant approvedAt;

    @Schema(description = "Scheduled follow-up reminder date")
    private LocalDate followUpReminderDate;

    @Schema(description = "Whether the follow-up reminder has been completed")
    private boolean reminderCompleted;

    @Schema(description = "Computed overdue indicator if followUpReminderDate < today and not completed")
    private boolean overdueReminder;

    @Schema(description = "Whether the initial draft was generated by AI")
    private boolean aiGenerated;

    @Schema(description = "AI provider used to draft the message")
    private String aiProvider;

    @Schema(description = "AI model used to draft the message")
    private String aiModelUsed;

    @Schema(description = "Whether the candidate edited the subject or body after creation")
    private boolean editedByUser;

    @Schema(description = "Creation UTC timestamp")
    private Instant createdAt;

    @Schema(description = "Last update UTC timestamp")
    private Instant updatedAt;
}

